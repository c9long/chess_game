import { z } from 'zod'
import {
  CLOSE_CODES,
  ERROR_CODES,
  MATCH_KINDS,
  MATCH_PHASES,
  PROTOCOL_VERSION,
  ROOM_NAMES,
  SEAT_NAMES,
  UNTIMED,
} from './constants.ts'
import {
  clientMessageSchemas,
  createOptionsSchema,
  joinOptionsSchema,
  lobbyMetadataSchema,
  RESERVED_MESSAGE_TYPES,
  serverMessageSchemas,
} from './messages.ts'
import {
  BLOCKS_MAX,
  blockBodySchema,
  REPORT_NOTE_MAX,
  REPORT_REASONS,
  REPORT_RESOLUTIONS,
  REPORTS_PER_DAY,
  reportBodySchema,
  resolveReportBodySchema,
} from './moderation.ts'
import {
  CHALLENGE_MAX_INVITEES,
  CHALLENGE_TTL_MS,
  challengeBodySchema,
  FRIEND_REQUESTS_OUTGOING_MAX,
  FRIEND_REQUESTS_PER_HOUR,
  FRIENDS_MAX,
  friendRequestBodySchema,
  SOCIAL_ERROR_CODES,
  socialMessageSchemas,
} from './social.ts'

function toSchema(schema: z.ZodType, io: 'input' | 'output') {
  return z.toJSONSchema(schema, { io, target: 'draft-2020-12', unrepresentable: 'any' })
}

function mapSchemas(record: Record<string, z.ZodType>, io: 'input' | 'output') {
  return Object.fromEntries(Object.entries(record).map(([k, v]) => [k, toSchema(v, io)]))
}

/**
 * The whole wire contract as one JSON document (JSON Schema 2020-12 per payload), for
 * generating C# types for the Unity client. The synced room state is a Colyseus schema;
 * generate it with `schema-codegen` from src/state.ts instead.
 */
export function buildProtocolJsonSchema() {
  return {
    $comment: 'Generated by `pnpm --filter @game/protocol schema`. Do not edit.',
    protocolVersion: PROTOCOL_VERSION,
    roomNames: ROOM_NAMES,
    seats: SEAT_NAMES,
    phases: MATCH_PHASES,
    matchKinds: MATCH_KINDS,
    untimed: UNTIMED,
    errorCodes: ERROR_CODES,
    closeCodes: CLOSE_CODES,
    reservedMessageTypes: RESERVED_MESSAGE_TYPES,
    joinOptions: {
      create: toSchema(createOptionsSchema, 'input'),
      join: toSchema(joinOptionsSchema, 'input'),
    },
    lobbyMetadata: toSchema(lobbyMetadataSchema, 'output'),
    clientMessages: mapSchemas(clientMessageSchemas, 'input'),
    serverMessages: mapSchemas(serverMessageSchemas, 'output'),
    social: {
      limits: {
        friendsMax: FRIENDS_MAX,
        outgoingRequestsMax: FRIEND_REQUESTS_OUTGOING_MAX,
        requestsPerHour: FRIEND_REQUESTS_PER_HOUR,
        challengeMaxInvitees: CHALLENGE_MAX_INVITEES,
        challengeTtlMs: CHALLENGE_TTL_MS,
      },
      errorCodes: SOCIAL_ERROR_CODES,
      restBodies: {
        friendRequest: toSchema(friendRequestBodySchema, 'input'),
        challenge: toSchema(challengeBodySchema, 'input'),
      },
      roomMessages: mapSchemas(socialMessageSchemas, 'output'),
    },
    moderation: {
      limits: {
        blocksMax: BLOCKS_MAX,
        reportsPerDay: REPORTS_PER_DAY,
        reportNoteMax: REPORT_NOTE_MAX,
      },
      reportReasons: REPORT_REASONS,
      reportResolutions: REPORT_RESOLUTIONS,
      restBodies: {
        block: toSchema(blockBodySchema, 'input'),
        report: toSchema(reportBodySchema, 'input'),
        resolveReport: toSchema(resolveReportBodySchema, 'input'),
      },
    },
  }
}
